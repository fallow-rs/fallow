import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

import {
  LINE_LIMIT,
  countLines,
  evaluateChange,
  isCheckedPath,
  isGeneratedSource,
  parseNameStatus,
} from "./check-file-size.mjs";

const SCRIPT = fileURLToPath(new URL("./check-file-size.mjs", import.meta.url));

const linesOf = (count, prefix = "line") =>
  Array.from({ length: count }, (_, index) => `${prefix} ${index}\n`).join("");

test("countLines matches wc -l and counts a last line without a newline", () => {
  assert.equal(countLines(""), 0);
  assert.equal(countLines("a\n"), 1);
  assert.equal(countLines("a\nb"), 2);
  assert.equal(countLines("a\n\nb\n"), 3);
});

test("isCheckedPath covers Rust, mjs and TypeScript but not snapshots", () => {
  assert.equal(isCheckedPath("crates/cli/src/main.rs"), true);
  assert.equal(isCheckedPath("scripts/tool.mjs"), true);
  assert.equal(isCheckedPath("npm/fallow/types/output-contract.d.ts"), true);
  assert.equal(isCheckedPath("docs/README.md"), false);
  assert.equal(isCheckedPath("crates/cli/src/snapshots/case.snap"), false);
  assert.equal(isCheckedPath("crates/cli/tests/snapshots/helper.rs"), false);
  assert.equal(isCheckedPath("src/__snapshots__/view.test.ts"), false);
});

test("isGeneratedSource reads the generator marker in the header only", () => {
  assert.equal(isGeneratedSource("/**\n * AUTOGENERATED FILE. DO NOT EDIT.\n */\n"), true);
  assert.equal(isGeneratedSource("// Generated from schema.json. Do not edit.\n"), true);
  assert.equal(isGeneratedSource("// Generated from schema.json.\nfn main() {}\n"), false);
  assert.equal(isGeneratedSource(`${linesOf(20)}// Generated. Do not edit.\n`), false);
});

test("a file at or under the limit can grow", () => {
  const change = {
    path: "src/a.rs",
    newText: linesOf(LINE_LIMIT),
    oldText: linesOf(10),
  };
  assert.equal(evaluateChange(change), null);
});

test("a file over the limit fails when it grows", () => {
  const violation = evaluateChange({
    path: "src/a.rs",
    newText: linesOf(LINE_LIMIT + 2),
    oldText: linesOf(LINE_LIMIT + 1),
  });
  assert.deepEqual(violation, {
    path: "src/a.rs",
    oldPath: "src/a.rs",
    lines: LINE_LIMIT + 2,
    previous: LINE_LIMIT + 1,
  });
});

test("a file that crosses the limit fails", () => {
  const violation = evaluateChange({
    path: "src/a.ts",
    newText: linesOf(LINE_LIMIT + 1),
    oldText: linesOf(LINE_LIMIT),
  });
  assert.equal(violation?.previous, LINE_LIMIT);
});

test("a file over the limit passes when it keeps its size or shrinks", () => {
  const oldText = linesOf(LINE_LIMIT + 50);
  assert.equal(evaluateChange({ path: "src/a.rs", newText: oldText, oldText }), null);
  assert.equal(
    evaluateChange({ path: "src/a.rs", newText: linesOf(LINE_LIMIT + 10), oldText }),
    null,
  );
});

test("a new file over the limit fails", () => {
  const violation = evaluateChange({
    path: "src/new.mjs",
    newText: linesOf(LINE_LIMIT + 1),
    oldText: null,
  });
  assert.equal(violation?.previous, null);
});

test("generated files and unchecked extensions are exempt", () => {
  const generated = `// Generated from schema.json. Do not edit.\n${linesOf(LINE_LIMIT + 5)}`;
  assert.equal(evaluateChange({ path: "src/gen.ts", newText: generated, oldText: null }), null);
  assert.equal(
    evaluateChange({ path: "docs/big.md", newText: linesOf(LINE_LIMIT + 5), oldText: null }),
    null,
  );
});

test("parseNameStatus reads plain and renamed entries", () => {
  const output = ["M", "src/a.rs", "R087", "src/old.rs", "src/new.rs", "A", "src/b.ts", ""].join(
    "\0",
  );
  assert.deepEqual(parseNameStatus(output), [
    { path: "src/a.rs", oldPath: "src/a.rs" },
    { path: "src/new.rs", oldPath: "src/old.rs" },
    { path: "src/b.ts", oldPath: "src/b.ts" },
  ]);
  assert.deepEqual(parseNameStatus(""), []);
});

// A repository with a private git config, so the settings of the person who
// runs the tests stay out of the fixture. A git hook exports GIT_DIR and
// GIT_INDEX_FILE, and those must not point the fixture at this repository.
const createRepo = (t) => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "check-file-size-")));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const globalConfig = join(root, "gitconfig");
  writeFileSync(
    globalConfig,
    "[user]\n\tname = Test\n\temail = test@example.invalid\n[commit]\n\tgpgsign = false\n[init]\n\tdefaultBranch = main\n",
  );
  const work = join(root, "work");
  mkdirSync(work);
  const env = { ...process.env, GIT_CONFIG_GLOBAL: globalConfig, GIT_CONFIG_NOSYSTEM: "1" };
  for (const name of ["GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR"]) {
    delete env[name];
  }
  const git = (...args) =>
    execFileSync("git", args, { cwd: work, env, encoding: "utf8", stdio: "pipe" }).trim();
  const write = (path, text) => {
    mkdirSync(dirname(join(work, path)), { recursive: true });
    writeFileSync(join(work, path), text);
  };
  const run = (...args) =>
    spawnSync(process.execPath, [SCRIPT, ...args], { cwd: work, env, encoding: "utf8" });
  git("init", "--quiet");
  return { git, write, run };
};

test("--staged fails a grown large file and names it", (t) => {
  const repo = createRepo(t);
  repo.write("src/big.rs", linesOf(LINE_LIMIT + 10));
  repo.git("add", "--all");
  repo.git("commit", "--quiet", "-m", "base");

  repo.write("src/big.rs", linesOf(LINE_LIMIT + 11));
  repo.git("add", "--all");
  const result = repo.run("--staged");

  assert.equal(result.status, 1, result.stderr);
  assert.match(result.stderr, /src\/big\.rs: 2011 lines, HEAD has 2010\./u);
  assert.match(result.stderr, /HK_SKIP_STEPS=file-size/u);
});

test("--staged measures the staged blob, not the working tree", (t) => {
  const repo = createRepo(t);
  repo.write("src/big.rs", linesOf(LINE_LIMIT + 10));
  repo.git("add", "--all");
  repo.git("commit", "--quiet", "-m", "base");

  repo.write("src/big.rs", linesOf(LINE_LIMIT + 5));
  repo.git("add", "--all");
  repo.write("src/big.rs", linesOf(LINE_LIMIT + 50));

  const result = repo.run("--staged");
  assert.equal(result.status, 0, result.stderr);
});

test("--staged passes a shrunk large file and fails a new large file", (t) => {
  const repo = createRepo(t);
  repo.write("src/big.rs", linesOf(LINE_LIMIT + 10));
  repo.git("add", "--all");
  repo.git("commit", "--quiet", "-m", "base");

  repo.write("src/big.rs", linesOf(LINE_LIMIT + 1));
  repo.git("add", "--all");
  assert.equal(repo.run("--staged").status, 0);

  repo.write("src/fresh.ts", linesOf(LINE_LIMIT + 1));
  repo.git("add", "--all");
  const result = repo.run("--staged");
  assert.equal(result.status, 1);
  assert.match(result.stderr, /src\/fresh\.ts: new file with 2001 lines\./u);
});

test("--staged compares a renamed file with its old path", (t) => {
  const repo = createRepo(t);
  repo.write("src/old.rs", linesOf(LINE_LIMIT + 10));
  repo.git("add", "--all");
  repo.git("commit", "--quiet", "-m", "base");

  repo.git("mv", "src/old.rs", "src/new.rs");
  assert.equal(repo.run("--staged").status, 0);

  repo.write("src/new.rs", linesOf(LINE_LIMIT + 11));
  repo.git("add", "--all");
  const result = repo.run("--staged");
  assert.equal(result.status, 1);
  assert.match(result.stderr, /HEAD \(src\/old\.rs\) has 2010/u);
});

test("--staged checks every file of a first commit", (t) => {
  const repo = createRepo(t);
  repo.write("src/big.rs", linesOf(LINE_LIMIT + 1));
  repo.git("add", "--all");
  assert.equal(repo.run("--staged").status, 1);
});

test("--base compares HEAD with the merge base", (t) => {
  const repo = createRepo(t);
  repo.write("src/big.rs", linesOf(LINE_LIMIT + 10));
  repo.git("add", "--all");
  repo.git("commit", "--quiet", "-m", "base");
  repo.git("checkout", "--quiet", "-b", "topic");
  repo.write("src/big.rs", linesOf(LINE_LIMIT + 12));
  repo.git("commit", "--quiet", "--all", "-m", "grow");
  // A later shrink on main must not hide the growth on the branch.
  repo.git("checkout", "--quiet", "main");
  repo.write("src/big.rs", linesOf(LINE_LIMIT + 2));
  repo.git("commit", "--quiet", "--all", "-m", "shrink on main");
  repo.git("checkout", "--quiet", "topic");

  const result = repo.run("--base", "main");
  assert.equal(result.status, 1, result.stderr);
  assert.match(result.stderr, /src\/big\.rs: 2012 lines, merge base [0-9a-f]{12} has 2010\./u);
  // The CI step has no skip route, so the message must not offer the hook skip.
  assert.doesNotMatch(result.stderr, /HK_SKIP_STEPS/u);
});

test("an unknown argument prints the usage and exits with 2", (t) => {
  const repo = createRepo(t);
  const result = repo.run("--all");
  assert.equal(result.status, 2);
  assert.match(result.stderr, /Usage: node scripts\/check-file-size\.mjs/u);
});
