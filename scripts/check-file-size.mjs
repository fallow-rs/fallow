#!/usr/bin/env node

// Stop large source files from growing. A change may shrink a file over the
// line limit or keep its size, but it must not add lines to it. A new file
// over the limit fails too. See docs/development/quality-gates.md#file-size.

import { execFileSync } from "node:child_process";
import { extname, resolve } from "node:path";
import { pathToFileURL } from "node:url";

/** The largest line count that a checked file can have without the no-growth rule. */
export const LINE_LIMIT = 2000;

const CHECKED_EXTENSIONS = new Set([".rs", ".mjs", ".ts"]);
const SNAPSHOT_DIRECTORIES = new Set(["snapshots", "__snapshots__"]);
// The repository generators write one of two exact header lines in the first
// lines of the file. A comment that only names the words does not match.
const GENERATED_HEADER_LINES = 10;
const GENERATED_HEADER =
  /^\s*(?:\/\/|\/\*+|\*|#)\s*(?:AUTOGENERATED FILE\. DO NOT EDIT\.|Generated (?:from|by) \S.*\. Do not edit\.)\s*(?:\*\/)?\s*$/u;
const SKIP_STEP = "file-size";
const GIT_MAX_BUFFER = 256 * 1024 * 1024;

const USAGE = `Usage: node scripts/check-file-size.mjs (--staged | --base <ref>)

  --staged      Compare each staged file with its HEAD version.
  --base <ref>  Compare each file that HEAD changes with its version at the
                merge base of HEAD and <ref>.`;

/** Counts lines the way `wc -l` does, plus a last line without a newline. */
export const countLines = (text) => {
  if (text === "") {
    return 0;
  }
  const newlines = text.split("\n").length - 1;
  return text.endsWith("\n") ? newlines : newlines + 1;
};

/** True when one of the first lines of the file is a generator header line. */
export const isGeneratedSource = (text) =>
  text.split("\n", GENERATED_HEADER_LINES).some((line) => GENERATED_HEADER.test(line));

/** True for a file that the no-growth rule checks. */
export const isCheckedPath = (path) => {
  if (!CHECKED_EXTENSIONS.has(extname(path).toLowerCase())) {
    return false;
  }
  return !path.split("/").some((segment) => SNAPSHOT_DIRECTORIES.has(segment));
};

/**
 * Applies the no-growth rule to one changed file.
 * `readPrevious` returns the line count of the earlier version, or null when
 * the file has no earlier version. The rule calls it only for a file over the
 * limit, so a small change reads no old blob.
 * Returns a violation, or null when the change passes.
 */
export const evaluateChange = ({ path, oldPath = path, newText, readPrevious }) => {
  if (!isCheckedPath(path)) {
    return null;
  }
  const lines = countLines(newText);
  if (lines <= LINE_LIMIT || isGeneratedSource(newText)) {
    return null;
  }
  const previous = readPrevious();
  if (previous === null) {
    return { path, lines, previous: null, oldPath };
  }
  return lines > previous ? { path, lines, previous, oldPath } : null;
};

/** Formats one violation as a message line. */
export const formatViolation = ({ path, lines, previous, oldPath }, baseLabel) => {
  if (previous === null) {
    return `${path}: new file with ${lines} lines. The limit for a new file is ${LINE_LIMIT} lines.`;
  }
  const source = oldPath === path ? baseLabel : `${baseLabel} (${oldPath})`;
  return `${path}: ${lines} lines, ${source} has ${previous}. A file over ${LINE_LIMIT} lines must not grow.`;
};

const git = (args) =>
  execFileSync("git", args, { encoding: "utf8", maxBuffer: GIT_MAX_BUFFER, stdio: "pipe" });

const readBlob = (spec) => {
  try {
    return git(["cat-file", "blob", spec]);
  } catch {
    return null;
  }
};

/**
 * The largest line count of the readable blobs, or null when no blob exists.
 * A merge commit has two parents. The largest parent version is the base, so
 * growth that the other parent brought in does not count against this commit.
 */
const readPreviousLines = (specs) => {
  const counts = specs
    .map(readBlob)
    .filter((text) => text !== null)
    .map(countLines);
  return counts.length === 0 ? null : Math.max(...counts);
};

const hasCommit = (ref) => {
  try {
    git(["rev-parse", "--verify", "--quiet", `${ref}^{commit}`]);
    return true;
  } catch {
    return false;
  }
};

/** Parses `git diff --name-status -z` output into `{ path, oldPath }` entries. */
export const parseNameStatus = (output) => {
  const fields = output.split("\0");
  const changes = [];
  let index = 0;
  while (index < fields.length && fields[index] !== "") {
    const status = fields[index];
    if (status.startsWith("R") || status.startsWith("C")) {
      changes.push({ oldPath: fields[index + 1], path: fields[index + 2] });
      index += 3;
    } else {
      changes.push({ oldPath: fields[index + 1], path: fields[index + 1] });
      index += 2;
    }
  }
  return changes;
};

const DIFF_ARGS = ["diff", "--name-status", "-z", "-M", "--diff-filter=AMR", "--no-ext-diff"];

const stagedChanges = () => {
  const oldCommit = hasCommit("HEAD") ? "HEAD" : null;
  const listed =
    oldCommit === null
      ? listInitialIndex()
      : parseNameStatus(git([...DIFF_ARGS, "--cached", oldCommit]));
  // During a merge, compare with both parents. The MERGE_HEAD version of a
  // renamed file uses the new path, because the rename is from HEAD.
  const mergeHead = oldCommit !== null && hasCommit("MERGE_HEAD") ? "MERGE_HEAD" : null;
  return {
    baseLabel: mergeHead === null ? "HEAD" : "HEAD or MERGE_HEAD",
    changes: listed.map(({ path, oldPath }) => ({
      path,
      oldPath,
      newSpec: `:${path}`,
      oldSpecs: [
        ...(oldCommit === null ? [] : [`${oldCommit}:${oldPath}`]),
        ...(mergeHead === null ? [] : [`${mergeHead}:${oldPath}`, `${mergeHead}:${path}`]),
      ],
    })),
  };
};

const listInitialIndex = () =>
  git(["ls-files", "-z", "--cached"])
    .split("\0")
    .filter((path) => path !== "")
    .map((path) => ({ path, oldPath: path }));

const baseChanges = (base) => {
  const mergeBase = git(["merge-base", "HEAD", base]).trim();
  return {
    baseLabel: `merge base ${mergeBase.slice(0, 12)}`,
    changes: parseNameStatus(git([...DIFF_ARGS, mergeBase, "HEAD"])).map(({ path, oldPath }) => ({
      path,
      oldPath,
      newSpec: `HEAD:${path}`,
      oldSpecs: [`${mergeBase}:${oldPath}`],
    })),
  };
};

/**
 * Reads each changed blob and returns one message per violation. It reads an
 * old blob only for a file over the limit, because a partial clone fetches
 * each missing blob over the network.
 */
export const collectViolations = ({ baseLabel, changes }) =>
  changes
    .filter(({ path }) => isCheckedPath(path))
    .flatMap(({ path, oldPath, newSpec, oldSpecs }) => {
      const newText = readBlob(newSpec);
      if (newText === null) {
        return [];
      }
      const readPrevious = () => readPreviousLines(oldSpecs);
      const violation = evaluateChange({ path, oldPath, newText, readPrevious });
      return violation === null ? [] : [formatViolation(violation, baseLabel)];
    });

/** Lists the changes for the mode, or returns an error message. */
const listChanges = (args) => {
  try {
    return { ok: true, data: args.mode === "staged" ? stagedChanges() : baseChanges(args.base) };
  } catch (error) {
    const detail = String(error?.stderr ?? error?.message ?? error).trim();
    const subject =
      args.mode === "staged" ? "the staged changes" : `the merge base with "${args.base}"`;
    return { ok: false, error: `file-size: cannot read ${subject}.\n${detail}` };
  }
};

const parseArgs = (argv) => {
  if (argv.length === 1 && argv[0] === "--staged") {
    return { ok: true, mode: "staged" };
  }
  if (argv.length === 2 && argv[0] === "--base" && argv[1] !== "") {
    return { ok: true, mode: "base", base: argv[1] };
  }
  return { ok: false };
};

/** Command-line entry point. Returns the exit code. */
export const main = (argv) => {
  const args = parseArgs(argv);
  if (!args.ok) {
    console.error(USAGE);
    return 2;
  }
  const staged = args.mode === "staged";
  const listed = listChanges(args);
  if (!listed.ok) {
    console.error(listed.error);
    return 2;
  }
  const violations = collectViolations(listed.data);
  if (violations.length === 0) {
    return 0;
  }
  // Only the pre-commit hook has a skip route. The CI step has none.
  const skipHint = staged
    ? [`To skip this step for one commit: HK_SKIP_STEPS=${SKIP_STEP} git commit`]
    : [];
  console.error(
    [
      `file-size: ${violations.length} file(s) over ${LINE_LIMIT} lines grew.`,
      ...violations.map((line) => `  ${line}`),
      "Move the new code to a new module, or remove lines from the file in the same change.",
      ...skipHint,
    ].join("\n"),
  );
  return 1;
};

const invokedPath =
  process.argv[1] === undefined ? null : pathToFileURL(resolve(process.argv[1])).href;
if (invokedPath === import.meta.url) {
  process.exitCode = main(process.argv.slice(2));
}
