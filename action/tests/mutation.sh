#!/usr/bin/env bash
printf 'fallow %s\n' "$*" >> "$MOCK_LOG"
if [ "${1:-}" = "--version" ]; then
  printf 'fallow %s\n' "${MOCK_FALLOW_VERSION:-3.42.0}"
  exit 0
fi
if [ "${1:-}" = "mutation" ] && [ "${2:-}" = "--help" ]; then
  [ -n "${MOCK_NO_MUTATION:-}" ] && exit 2
  printf 'Usage: fallow mutation [OPTIONS]\n'
  exit 0
fi
if [ "${1:-}" = "mutation" ]; then
  env | grep -E '^(GH_TOKEN|GITHUB_TOKEN|GITLAB_TOKEN|FALLOW_MUTATION_GH_TOKEN|ACTIONS_ID_TOKEN_REQUEST_TOKEN|GITHUB_ENV|GITHUB_OUTPUT|GITHUB_STEP_SUMMARY|BASH_ENV)=' \
    | sed 's/=.*/=<leaked>/' >> "$MOCK_LOG"
  out=""
  prev=""
  for arg in "$@"; do
    [ "$prev" = "-o" ] && out=$arg
    prev=$arg
  done
  [ -n "${MOCK_MUTATION_REPORT:-}" ] && [ -n "$out" ] && cp "$MOCK_MUTATION_REPORT" "$out"
  [ -n "${MOCK_MUTATION_STDOUT:-}" ] && printf '%s\n' "$MOCK_MUTATION_STDOUT"
  exit "${MOCK_MUTATION_EXIT:-0}"
fi
if [ "${1:-}" = "report" ]; then
  format=""
  prev=""
  for arg in "$@"; do
    [ "$prev" = "--format" ] && format=$arg
    prev=$arg
  done
  case "$format" in
    review-github)
      printf '{"meta":{"schema":"fallow-review-envelope/v3","provider":"github"},"body":"<!-- fallow-review -->","comments":[]}\n'
