# Runs analyze.sh with a mutation report. The remaining arguments are
# VAR=value pairs. Sets AM_GATE_EXIT, AM_GATE_STDOUT and AM_GATE_OUTPUTS.
am_gate_analyze() {
  local report=$1
  shift
  local run_dir
  run_dir=$(mktemp -d "$AM_GATE_WORK/run.XXXXXX")
  : > "$run_dir/github_output"
  set +e
  AM_GATE_STDOUT=$(
    cd "$run_dir" \
      && PATH="$AM_GATE_WORK/bin:$PATH" \
      GITHUB_OUTPUT="$run_dir/github_output" \
      GITHUB_ENV="$run_dir/github_env" \
      GITHUB_STEP_SUMMARY="$run_dir/step_summary" \
      RUNNER_TEMP="$run_dir" \
      INPUT_ROOT="." INPUT_FORMAT="json" INPUT_ARTIFACTS_DIR="." \
      INPUT_COMMAND="dead-code" INPUT_FAIL_ON_ISSUES="false" \
      FALLOW_MUTATION_RESULTS_FILE="$report" \
      env "$@" bash "$AM_SCRIPTS/analyze.sh" 2>&1
  )
  AM_GATE_EXIT=$?
  set -e
  AM_GATE_OUTPUTS=$(cat "$run_dir/github_output")
}

