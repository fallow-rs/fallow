# --- The result step maps the outcomes ---

W="$AM_TMP/tool"
am_run "$W" run EVENT_NAME=push FALLOW_MUTATION_SCOPE=all MOCK_MUTATION_EXIT=2 \
  MOCK_MUTATION_STDOUT='{"error":true,"message":"the worktree has changes\n100% dirty","exit_code":2,"code":"FALLOW_MUTATION_DIRTY_WORKTREE"}' > /dev/null
am_assert_eq "$(am_output "$W" outcome)" "tool-failed" "action mutation: exit code 2 is a tool failure"
am_assert_eq "$(jq -c 'keys' "$W/fallow-mutation-status.json")" '["exit_code","not_run_reason","outcome"]' \
  "action mutation: a tool failure puts no free text in the status file"
am_assert_eq "$(jq -r '.code' "$W/fallow-mutation.json")" "FALLOW_MUTATION_DIRTY_WORKTREE" "action mutation: the report file holds the error envelope"
RC=$(am_run "$W" gate FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json" FALLOW_MUTATION_RESULTS_FILE="$W/fallow-mutation.json")
am_assert_eq "$RC" "2" "action mutation: exit code 2 fails the result step"
AM_ERRORS=$(grep -c '^::error' "$W/stdout.log" || true)
am_assert_eq "$AM_ERRORS" "1" "action mutation: a tool failure has one error line"
assert_contains "$(cat "$W/stdout.log")" "::error title=Fallow mutation::fallow mutation failed (outcome tool-failed, exit code 2, FALLOW_MUTATION_DIRTY_WORKTREE): the worktree has changes%0A100%25 dirty" \
  "action mutation: the tool failure line is escaped and names the outcome and the code"

W="$AM_TMP/gate"
am_run "$W" run EVENT_NAME=push FALLOW_MUTATION_SCOPE=all FALLOW_MUTATION_MIN_SCORE=80 MOCK_MUTATION_EXIT=1 \
  MOCK_MUTATION_REPORT="$AM_TMP/mutation-gate-fail.json" > /dev/null
RC=$(am_run "$W" gate FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json")
am_assert_eq "$RC" "1" "action mutation: a failed score gate fails the result step with 1"
assert_contains "$(cat "$W/stdout.log")" "::error title=Fallow mutation::" "action mutation: a failed gate has an error line"
assert_contains "$(cat "$W/stdout.log")" "gate-failed" "action mutation: the gate error names the outcome"
assert_contains "$(cat "$W/stdout.log")" "exit code 1" "action mutation: the gate error names the exit code"

W="$AM_TMP/signal"
am_run "$W" run EVENT_NAME=push FALLOW_MUTATION_SCOPE=all MOCK_MUTATION_EXIT=130 > /dev/null
am_assert_eq "$(am_output "$W" outcome)" "interrupted" "action mutation: a signal is an interruption"
am_assert_eq "$(am_env "$W" FALLOW_MUTATION_NOT_RUN)" "interrupted" "action mutation: an interruption without a report exports the interrupted reason"
