#!/usr/bin/env bash
# Tests of the Action mutation step (action/scripts/mutation.sh), its comment
# section and its action.yml wiring. action/tests/run.sh sources this file,
# so it uses the pass, fail and assert helpers and the DIR variable of run.sh.
# ci/tests/mutation.sh tests the shared helpers in depth.

echo ""
echo "=== Mutation testing ==="

AM_SCRIPTS="$DIR/../scripts"
AM_FIXTURES="$DIR/../../ci/tests/fixtures"
AM_TMP=$(mktemp -d)
AM_BIN="$AM_TMP/bin"
mkdir -p "$AM_BIN"

am_assert_eq() {
  local actual="$1" expected="$2" name="$3"
  if [ "$actual" = "$expected" ]; then
    pass "$name"
  else
    fail "$name" "expected '$expected', got '$actual'"
  fi
}

# A fake `fallow` for the mutation run, the PR comment render and the post.
cat > "$AM_BIN/fallow" <<'SH'
#!/usr/bin/env bash
printf 'fallow %s\n' "$*" >> "$MOCK_LOG"
if [ "${1:-}" = "mutation" ] && [ "${2:-}" = "tasks" ]; then
  [ -n "${MOCK_MUTATION_TASKS:-}" ] && cat "$MOCK_MUTATION_TASKS"
  exit 0
fi
if [ "${1:-}" = "mutation" ]; then
  out=""
  prev=""
  for arg in "$@"; do
    [ "$prev" = "-o" ] && out=$arg
    prev=$arg
  done
  [ -n "${MOCK_MUTATION_REPORT:-}" ] && [ -n "$out" ] && cp "$MOCK_MUTATION_REPORT" "$out"
  [ -n "${MOCK_MUTATION_STDOUT:-}" ] && printf '%s\n' "$MOCK_MUTATION_STDOUT"
  exit "${MOCK_MUTATION_EXIT:-0}"
fi
if [ "${1:-}" = "report" ]; then
  body=$(printf '<!-- fallow-id: fallow-results -->\n# Fallow report\n\nNo findings.\n\nGenerated by fallow.\n')
  printf '%s\n' "$body"
  if [ -n "${FALLOW_PR_COMMENT_ENVELOPE_FILE:-}" ]; then
    jq -n --arg b "$body"$'\n' '{marker_id: "fallow-results", body: $b, is_clean: true, details_url: null, check_summary: null, truncation: {truncated: false, shown_findings: 0, total_findings: 0}}' \
      > "$FALLOW_PR_COMMENT_ENVELOPE_FILE"
  fi
  exit 0
fi
if [ "${1:-}" = "ci" ] && [ "${2:-}" = "post-pr-comment" ]; then
  prev=""
  for arg in "$@"; do
    [ "$prev" = "--envelope" ] && cp "$arg" "$MOCK_CAPTURE_ENVELOPE"
    prev=$arg
  done
  printf '{"action":"create","marker_id":"fallow-results"}\n'
  exit 0
fi
exit 0
SH
chmod +x "$AM_BIN/fallow"

cat > "$AM_BIN/gh" <<'SH'
#!/usr/bin/env bash
printf 'gh %s\n' "$*" >> "$MOCK_LOG"
if [ "${1:-}" = "pr" ] && [ "${2:-}" = "diff" ]; then
  printf 'diff --git a/src/a.js b/src/a.js\n--- a/src/a.js\n+++ b/src/a.js\n@@ -0,0 +1 @@\n+export const a = 1;\n'
fi
exit 0
SH
chmod +x "$AM_BIN/gh"

# Runs `mutation.sh <mode>` in a work directory. The remaining arguments are
# VAR=value pairs. Prints the exit code; the step outputs go to
# $work/github-output.
am_run() {
  local work=$1 mode=$2
  shift 2
  mkdir -p "$work"
  (
    cd "$work" || exit 99
    for pair in "$@"; do export "${pair?}"; done
    export PATH="$AM_BIN:$PATH" MOCK_LOG="$work/mock.log" RUNNER_TEMP="$AM_TMP"
    export GITHUB_OUTPUT="$work/github-output" GITHUB_STEP_SUMMARY="$work/summary.md"
    bash "$AM_SCRIPTS/mutation.sh" "$mode" > "$work/stdout.log" 2>&1
    printf '%s' "$?"
  )
}

am_output() {
  sed -n "s/^$2=//p" "$1/github-output" | tail -n 1
}

# --- Fork refusal ---

W="$AM_TMP/fork-target"
RC=$(am_run "$W" run EVENT_NAME=pull_request_target PR_NUMBER=12 PR_HEAD_REPO=someone/fork GH_REPO=owner/repo \
  FALLOW_MUTATION_SCOPE=changed MOCK_MUTATION_REPORT="$AM_FIXTURES/mutation-clean.json")
am_assert_eq "$RC" "0" "action mutation: the run step exits 0 so the analysis still runs"
am_assert_eq "$(am_output "$W" outcome)" "refused" "action mutation: a fork PR with base secrets (pull_request_target) is refused"
am_assert_eq "$(cat "$W/mock.log" 2>/dev/null | grep -c '^fallow mutation')" "0" "action mutation: a refused run never starts the tests"
am_assert_eq "$(am_output "$W" cache_save)" "false" "action mutation: a refused run saves no cache"
RC=$(am_run "$W" gate FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json" FALLOW_MUTATION_SECTION_FILE="$W/fallow-mutation-section.md")
am_assert_eq "$RC" "2" "action mutation: the result step fails for a refusal"
assert_contains "$(cat "$W/stdout.log")" "::error title=Fallow mutation::Mutation testing did not run." "action mutation: a refusal has a clear error"
assert_contains "$(cat "$W/summary.md")" "## Mutation testing" "action mutation: the job summary gets the section"

W="$AM_TMP/fork-pr"
mkdir -p "$W/.fallow/mutation"
printf '{}\n' > "$W/.fallow/mutation/results.json"
am_run "$W" run EVENT_NAME=pull_request PR_NUMBER=12 PR_HEAD_REPO=someone/fork GH_REPO=owner/repo \
  FALLOW_MUTATION_SCOPE=changed MOCK_MUTATION_REPORT="$AM_FIXTURES/mutation-clean.json" > /dev/null
am_assert_eq "$(am_output "$W" outcome)" "ok" "action mutation: a fork PR in a pull_request workflow runs"
am_assert_eq "$(am_output "$W" cache_save)" "false" "action mutation: a fork PR never saves the result cache"

for event in issue_comment workflow_run pull_request_target; do
  W="$AM_TMP/event-$event"
  am_run "$W" run EVENT_NAME="$event" GH_REPO=owner/repo FALLOW_MUTATION_SCOPE=all \
    MOCK_MUTATION_REPORT="$AM_FIXTURES/mutation-clean.json" > /dev/null
  am_assert_eq "$(am_output "$W" outcome)" "refused" \
    "action mutation: a ${event} job without a fork PR payload is refused"
done
W="$AM_TMP/event-push"
am_run "$W" run EVENT_NAME=push GH_REPO=owner/repo FALLOW_MUTATION_SCOPE=all \
  MOCK_MUTATION_REPORT="$AM_FIXTURES/mutation-clean.json" > /dev/null
am_assert_eq "$(am_output "$W" outcome)" "ok" "action mutation: a push job runs"

# --- Stale result files ---

W="$AM_TMP/stale"
am_run "$W" run EVENT_NAME=push FALLOW_MUTATION_SCOPE=all MOCK_MUTATION_REPORT="$AM_FIXTURES/mutation-partial.json" > /dev/null
am_run "$W" run EVENT_NAME=pull_request_target FALLOW_MUTATION_SCOPE=all > /dev/null
am_assert_eq "$(am_output "$W" results)" "" "action mutation: a later refused run does not report the report of an earlier run"
[ ! -f "$W/fallow-mutation.json" ] && pass "action mutation: the step removes result files of an earlier run" \
  || fail "action mutation: the step removes result files of an earlier run" "fallow-mutation.json still exists"

# --- A report of an unknown shape ---

W="$AM_TMP/badshape"
printf '{"completion":"oops","summary":{"counts":{}}}\n' > "$AM_TMP/badshape.json"
RC=$(am_run "$W" run EVENT_NAME=push FALLOW_MUTATION_SCOPE=all FALLOW_MUTATION_MIN_SCORE=90 MOCK_MUTATION_EXIT=1 \
  MOCK_MUTATION_REPORT="$AM_TMP/badshape.json")
am_assert_eq "$(am_output "$W" outcome)" "tool-failed" "action mutation: a report of an unknown shape is a tool failure"
RC=$(am_run "$W" gate FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json" FALLOW_MUTATION_SECTION_FILE="$W/fallow-mutation-section.md")
am_assert_eq "$RC" "2" "action mutation: a failed gate with an unreadable report still fails the job"

# --- Invalid input ---

W="$AM_TMP/invalid"
am_run "$W" run EVENT_NAME=push FALLOW_MUTATION_SCOPE=all "FALLOW_MUTATION_TIME_BUDGET=1m --allow-dirty" > /dev/null
am_assert_eq "$(am_output "$W" outcome)" "invalid-input" "action mutation: a bad input has its own outcome"
RC=$(am_run "$W" gate FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json" FALLOW_MUTATION_SECTION_FILE="$W/fallow-mutation-section.md")
am_assert_eq "$RC" "2" "action mutation: a bad input fails the result step"
assert_contains "$(cat "$W/stdout.log")" "The mutation testing input is invalid." "action mutation: a bad input is not reported as an exit code of fallow"
assert_not_contains "$(cat "$W/stdout.log")" "failed with exit code" "action mutation: a bad input names no exit code"

# --- Same-repository PR ---

W="$AM_TMP/same-repo"
mkdir -p "$W/.fallow/mutation"
printf '{}\n' > "$W/.fallow/mutation/results.json"
am_run "$W" run EVENT_NAME=pull_request PR_NUMBER=12 PR_HEAD_REPO=owner/repo GH_REPO=owner/repo \
  FALLOW_MUTATION_SCOPE=changed FALLOW_MUTATION_TIME_BUDGET=10m \
  MOCK_MUTATION_REPORT="$AM_FIXTURES/mutation-partial.json" MOCK_MUTATION_TASKS="$AM_FIXTURES/mutation-tasks.json" > /dev/null
LOG=$(cat "$W/mock.log")
assert_contains "$LOG" "gh pr diff 12 --repo owner/repo" "action mutation: changed scope reads the PR diff"
assert_contains "$LOG" "--diff-file $AM_TMP/fallow-mutation-pr.diff" "action mutation: the PR diff goes to the runner temp directory"
assert_not_contains "$LOG" "--allow-dirty" "action mutation: never passes --allow-dirty"
am_assert_eq "$(am_output "$W" outcome)" "ok" "action mutation: outcome output"
am_assert_eq "$(am_output "$W" completion)" "partial" "action mutation: completion output"
am_assert_eq "$(am_output "$W" score)" "50" "action mutation: score output in percent"
am_assert_eq "$(am_output "$W" results)" "./fallow-mutation.json" "action mutation: results output"
am_assert_eq "$(am_output "$W" cache_save)" "true" "action mutation: a same-repository PR saves the result cache"
RC=$(am_run "$W" gate FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json" FALLOW_MUTATION_SECTION_FILE="$W/fallow-mutation-section.md")
am_assert_eq "$RC" "0" "action mutation: a partial run passes the result step"

# --- The result step maps the exit codes ---

W="$AM_TMP/tool"
am_run "$W" run EVENT_NAME=push FALLOW_MUTATION_SCOPE=all MOCK_MUTATION_EXIT=2 \
  MOCK_MUTATION_STDOUT='{"error":true,"message":"the worktree has changes\n100% dirty","exit_code":2,"code":"FALLOW_MUTATION_DIRTY_WORKTREE"}' > /dev/null
RC=$(am_run "$W" gate FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json" FALLOW_MUTATION_SECTION_FILE="$W/fallow-mutation-section.md")
am_assert_eq "$RC" "2" "action mutation: exit code 2 fails the result step"
assert_contains "$(cat "$W/stdout.log")" "::error title=Fallow mutation::fallow mutation failed with exit code 2 (FALLOW_MUTATION_DIRTY_WORKTREE): the worktree has changes%0A100%25 dirty" \
  "action mutation: a tool failure has one escaped error line"

W="$AM_TMP/gate"
am_run "$W" run EVENT_NAME=push FALLOW_MUTATION_SCOPE=all FALLOW_MUTATION_MIN_SCORE=80 MOCK_MUTATION_EXIT=1 \
  MOCK_MUTATION_REPORT="$AM_FIXTURES/mutation-partial.json" > /dev/null
RC=$(am_run "$W" gate FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json" FALLOW_MUTATION_SECTION_FILE="$W/fallow-mutation-section.md")
am_assert_eq "$RC" "1" "action mutation: a failed score gate fails the result step with 1"
assert_contains "$(cat "$W/stdout.log")" "The mutation score 50% is lower than the minimum of 80%." "action mutation: the score gate error names both values"

RC=$(am_run "$AM_TMP/nostatus" gate FALLOW_MUTATION_STATUS_FILE="$AM_TMP/missing.json")
am_assert_eq "$RC" "2" "action mutation: a missing status file fails the result step"

# --- The section in the sticky comment ---

W="$AM_TMP/comment"
mkdir -p "$W"
printf '{"kind":"dead-code","schema_version":9}\n' > "$W/fallow-results.json"
printf '## Mutation testing\n\nsection text\n' > "$W/section.md"
(
  cd "$W" || exit 99
  PATH="$AM_BIN:$PATH" MOCK_LOG="$W/mock.log" MOCK_CAPTURE_ENVELOPE="$W/posted.json" \
    GH_TOKEN=test PR_NUMBER=12 GH_REPO=owner/repo FALLOW_COMMAND=check \
    FALLOW_DIFF_FILE="$W/none.diff" \
    FALLOW_MUTATION_SECTION_FILE="$W/section.md" FALLOW_MUTATION_CLEAN=false \
    bash "$AM_SCRIPTS/comment.sh" > "$W/comment.out" 2>&1
)
POSTED=$(jq -r '.body' "$W/posted.json" 2>/dev/null)
assert_contains "$POSTED" $'section text\n\nGenerated by fallow.' "action comment: the posted body has the section above the footer"
am_assert_eq "$(grep -c '^## Mutation testing' "$W/fallow-pr-comment.md")" "1" "action comment: one section, in the same sticky comment"
am_assert_eq "$(jq -r '.is_clean' "$W/posted.json" 2>/dev/null)" "false" "action comment: open mutation items create the comment"

# --- action.yml wiring ---

ACTION_YML=$(cat "$DIR/../../action.yml")
for input in mutation mutation-scope mutation-time-budget mutation-max-mutants mutation-min-score; do
  assert_contains "$ACTION_YML" "  ${input}:" "action.yml exposes the ${input} input"
done
assert_contains "$ACTION_YML" "FALLOW_MUTATION_TIME_BUDGET: \${{ inputs.mutation-time-budget }}" "action.yml maps the time budget"
assert_contains "$ACTION_YML" "!\${{ inputs.root }}/.fallow/mutation" "action.yml keeps the mutation cache out of the analysis cache"
assert_contains "$ACTION_YML" "if: always() && steps.mutation.outputs.cache_save == 'true'" "action.yml saves the mutation cache only when the step allows it"
assert_contains "$ACTION_YML" "FALLOW_MUTATION_SECTION_FILE: \${{ steps.mutation.outputs.section }}" "action.yml passes the section to the comment step"
assert_contains "$ACTION_YML" "-\${{ github.run_id }}-\${{ github.run_attempt }}" "action.yml gives each run attempt its own mutation cache entry"
assert_not_contains "$ACTION_YML" "--allow-dirty" "action.yml never passes --allow-dirty"
STEP_ORDER=$(ruby -ryaml -e 'puts YAML.load_file(ARGV[0])["runs"]["steps"].map { |s| s["name"] }' "$DIR/../../action.yml" 2>/dev/null | tr '\n' '|')
if [ -n "$STEP_ORDER" ]; then
  case "$STEP_ORDER" in
    *"Restore mutation result cache|Run mutation testing|Save mutation result cache|Run analysis|"*) pass "action.yml runs mutation before the analysis" ;;
    *) fail "action.yml runs mutation before the analysis" "step order: $STEP_ORDER" ;;
  esac
  case "$STEP_ORDER" in
    *"|Mutation testing result|") pass "action.yml applies the mutation result in the last step" ;;
    *) fail "action.yml applies the mutation result in the last step" "step order: $STEP_ORDER" ;;
  esac
else
  echo "  - action.yml step order check skipped: ruby is not installed"
fi

rm -rf "$AM_TMP"
