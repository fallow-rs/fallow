# Tests of the Action mutation step (action/scripts/mutation.sh), the mutation
# arguments of the render steps, the gate merge of analyze.sh and the
# action.yml wiring. action/tests/run.sh sources this file, so it uses the
# pass, fail and assert helpers and the DIR variable of run.sh.
# ci/tests/mutation.sh tests the shared helpers in depth.

