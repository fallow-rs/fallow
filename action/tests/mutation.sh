# The env block of one step, from its `- name:` line to the next one.
am_step_block() {
  awk -v name="$1" '
    /^    - name: / { inside = ($0 == "    - name: " name) }
    inside { print }
  ' "$AM_ROOT/action.yml"
}
assert_contains "$(am_step_block 'Resolve change scope')" "GH_TOKEN: \${{ inputs.github-token }}" "action.yml gives the scope step the token"
assert_contains "$(am_step_block 'Resolve change scope')" "if: always()" "action.yml always runs the scope step"
assert_not_contains "$(am_step_block 'Run mutation testing')" "GH_TOKEN" "action.yml gives the mutation step no token"

AM_STEPS=$(awk '/^    - name: / { sub(/^    - name: /, ""); print }' "$AM_ROOT/action.yml")
am_step_index() {
  awk -v name="$1" '$0 == name { print NR; found = 1; exit } END { if (!found) print 0 }' <<< "$AM_STEPS"
}
AM_SCOPE=$(am_step_index 'Resolve change scope')
AM_RESTORE=$(am_step_index 'Restore mutation result cache')
AM_RUN=$(am_step_index 'Run mutation testing')
AM_SAVE=$(am_step_index 'Save mutation result cache')
AM_ANALYSIS=$(am_step_index 'Run analysis')
AM_RESULT=$(am_step_index 'Mutation testing result')
AM_LAST=$(wc -l <<< "$AM_STEPS" | tr -d ' ')
if [ "$AM_SCOPE" -gt 0 ] && [ "$AM_SCOPE" -lt "$AM_RESTORE" ] && [ "$AM_RESTORE" -lt "$AM_RUN" ] \
    && [ "$AM_RUN" -lt "$AM_SAVE" ] && [ "$AM_SAVE" -lt "$AM_ANALYSIS" ]; then
  pass "action.yml runs scope, restore, mutation, save and analysis in order"
else
  fail "action.yml runs scope, restore, mutation, save and analysis in order" "steps: $(tr '\n' '|' <<< "$AM_STEPS")"
fi
am_assert_eq "$AM_RESULT" "$AM_LAST" "action.yml applies the mutation result in the last step"
if [ "$AM_LAST" -ge 10 ]; then
  pass "action.yml step order check reads the steps"
else
  fail "action.yml step order check reads the steps" "only $AM_LAST steps"
fi

