RC=$(am_run "$W" gate FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json")
am_assert_eq "$RC" "2" "action mutation: the result step fails for a refusal"
assert_contains "$(cat "$W/stdout.log")" "::error title=Fallow mutation::" "action mutation: a refusal has an error line"
assert_contains "$(cat "$W/stdout.log")" "event-refused" "action mutation: the refusal error names the reason"
[ ! -s "$W/summary.md" ] && pass "action mutation: the result step writes nothing to the job summary" \
  || fail "action mutation: the result step writes nothing to the job summary" "$(cat "$W/summary.md")"

