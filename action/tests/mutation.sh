am_load_env "$W"
for script in comment.sh review.sh summary.sh annotate.sh; do
  RW="$W/$script.d"
  am_render "$RW" "$script" HAS_MUTATION_REPORT=true "${AM_RUN_ENV[@]}"
  assert_contains "$(am_report_lines "$RW")" "--mutation-not-run event-refused" \
    "action render: $script passes --mutation-not-run event-refused for pull_request_target"
  assert_not_contains "$(am_report_lines "$RW")" "--mutation-report" \
    "action render: $script passes no report for a refused run"
