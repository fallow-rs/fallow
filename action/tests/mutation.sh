  am_render "$RW" "$script" HAS_MUTATION_REPORT=false INPUT_MUTATION=true MOCK_FALLOW_VERSION=3.41.0 "${AM_RUN_ENV[@]}"
  assert_contains "$(am_report_lines "$RW")" "fallow report --from" \
    "action render: $script still renders the analysis with an older CLI"
  assert_not_contains "$(am_report_lines "$RW")" "--mutation" \
    "action render: $script passes no mutation flag to an older CLI"
