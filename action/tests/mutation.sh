# Runs `mutation.sh <mode>` in a work directory. The remaining arguments are
# VAR=value pairs. Prints the exit code. The step outputs go to
# $work/github-output, and the GITHUB_ENV lines go to $work/github-env.
am_run() {
  local work=$1 mode=$2
  shift 2
  mkdir -p "$work"
  (
    cd "$work" || exit 99
    for pair in "$@"; do export "${pair?}"; done
    export PATH="$AM_BIN:$PATH" MOCK_LOG="$work/mock.log" RUNNER_TEMP="$AM_TMP"
    export GITHUB_OUTPUT="$work/github-output" GITHUB_STEP_SUMMARY="$work/summary.md"
    export GITHUB_ENV="$work/github-env"
    rc=0
    bash "$AM_SCRIPTS/mutation.sh" "$mode" > "$work/stdout.log" 2>&1 || rc=$?
    printf '%s' "$rc"
  )
}

am_output() {
  sed -n "s/^$2=//p" "$1/github-output" | tail -n 1
}

am_env() {
  sed -n "s/^$2=//p" "$1/github-env" | tail -n 1
}

# Sets AM_RUN_ENV to the GITHUB_ENV lines of a run step as VAR=value
# arguments, so a later render step in the test sees them as a composite step
# does.
am_load_env() {
  AM_RUN_ENV=()
  local line
  [ -f "$1/github-env" ] || return 0
  while IFS= read -r line; do
    AM_RUN_ENV+=("$line")
  done < "$1/github-env"
}

# Runs a render script (comment.sh, review.sh, summary.sh or annotate.sh) in a
# work directory with the stub on PATH. The remaining arguments are VAR=value
# pairs. Writes the output to $work/<script>.out and the summary to
# $work/summary.md.
am_render() {
  local work=$1 script=$2
  shift 2
  mkdir -p "$work"
  [ -f "$work/fallow-results.json" ] || printf '{"kind":"dead-code","schema_version":9}\n' > "$work/fallow-results.json"
  (
    cd "$work" || exit 99
    export GH_TOKEN=test PR_NUMBER=12 GH_REPO=owner/repo FALLOW_COMMAND=check
    export FALLOW_ROOT=. INPUT_ROOT=. MAX_ANNOTATIONS=50 ACTION_JQ_DIR="$DIR/../jq"
    export FALLOW_RESULTS_FILE="$work/fallow-results.json" HAS_NATIVE_REPORT=true
    export FALLOW_DIFF_FILE="$work/none.diff"
    # summary.sh and annotate.sh run $FALLOW_BIN before PATH, and the CI job
    # of the current binary sets it, so the stub must win here.
    export FALLOW_BIN="$AM_BIN/fallow"
    for pair in "$@"; do export "${pair?}"; done
    export PATH="$AM_BIN:$PATH" MOCK_LOG="$work/mock.log" GITHUB_STEP_SUMMARY="$work/summary.md"
    bash "$AM_SCRIPTS/$script" > "$work/$script.out" 2>&1
  )
}

