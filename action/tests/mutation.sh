  am_render "$RW" "$script" HAS_MUTATION_REPORT=true "${AM_RUN_ENV[@]}" \
    FALLOW_MUTATION_RESULTS_FILE="$W/fallow-mutation.json" FALLOW_MUTATION_STATUS_FILE="$W/fallow-mutation-status.json"
  assert_contains "$(am_report_lines "$RW")" "--mutation-report $W/fallow-mutation.json" \
    "action render: $script passes --mutation-report to fallow report"
