//! Splits analysis results into the parts that a merge combines.

use super::*;

/// Exhaustively destructure `other` into the five grouped merge-part structs.
///
/// The single exhaustive `let Self { .. }` lives here so that adding a field to
/// [`AnalysisResults`] becomes a compile error (a field must be routed into one
/// of the part structs) instead of being silently dropped during a merge. See
/// issue #444.
#[expect(
    clippy::too_many_lines,
    reason = "irreducible single exhaustive field-routing: the one `let Self { .. }` destructure must name every field so a newly added field is a compile error (issue #444); splitting it would defeat that exhaustiveness guarantee"
)]
pub(super) fn split_merge_parts(
    other: AnalysisResults,
) -> (
    AnalysisResultsCoreMergeParts,
    AnalysisResultsGraphMergeParts,
    AnalysisResultsWorkspaceMergeParts,
    AnalysisResultsFrameworkMergeParts,
    AnalysisResultsMetadataMergeParts,
) {
    let AnalysisResults {
        shared_state,
        unused_files,
        unused_exports,
        unused_types,
        private_type_leaks,
        deprecated_exports_in_use,
        unused_dependencies,
        unused_dev_dependencies,
        unused_optional_dependencies,
        unused_enum_members,
        unused_class_members,
        unused_namespace_members,
        unused_store_members,
        unresolved_imports,
        unlisted_dependencies,
        unlisted_binaries,
        duplicate_exports,
        duplicate_export_aliases,
        type_only_dependencies,
        test_only_dependencies,
        dev_dependencies_in_production,
        circular_dependencies,
        re_export_cycles,
        package_cycles,
        boundary_violations,
        boundary_coverage_violations,
        boundary_call_violations,
        policy_violations,
        stale_suppressions,
        unused_catalog_entries,
        empty_catalog_groups,
        unresolved_catalog_references,
        unused_dependency_overrides,
        misconfigured_dependency_overrides,
        invalid_client_exports,
        mixed_client_server_barrels,
        misplaced_directives,
        unprovided_injects,
        unrendered_components,
        route_collisions,
        dynamic_segment_name_conflicts,
        unused_component_props,
        absent_component_props,
        constant_parameters,
        unused_component_emits,
        unused_component_inputs,
        unused_component_outputs,
        unused_svelte_events,
        unused_effect_layers,
        unused_tagged_errors,
        unproduced_catch_tags,
        unused_server_actions,
        unused_load_data_keys,
        unused_load_data_keys_global_abstain,
        prop_drilling_chains,
        thin_wrappers,
        duplicate_prop_shapes,
        cascade_hidden,
        cascade,
        suppression_count,
        unused_component_props_exempted,
        active_suppressions,
        feature_flags,
        security_findings,
        suppressed_security_findings,
        security_unresolved_edge_files,
        security_unresolved_callee_sites,
        security_unresolved_callee_diagnostics,
        export_usages,
        entry_point_summary,
        render_fan_in,
        react_component_intel,
        semantic_reachable_files,
        semantic_framework_contracts,
        constant_parameter_candidates,
    } = other;

    (
        AnalysisResultsCoreMergeParts {
            unused_files,
            unused_exports,
            unused_types,
            private_type_leaks,
            deprecated_exports_in_use,
            unused_enum_members,
            unused_class_members,
            unused_namespace_members,
            unused_store_members,
            unresolved_imports,
            boundary_violations,
            boundary_coverage_violations,
            boundary_call_violations,
            policy_violations,
            stale_suppressions,
        },
        AnalysisResultsGraphMergeParts {
            unused_dependencies,
            unused_dev_dependencies,
            unused_optional_dependencies,
            unlisted_dependencies,
            unlisted_binaries,
            duplicate_exports,
            duplicate_export_aliases,
            type_only_dependencies,
            test_only_dependencies,
            dev_dependencies_in_production,
            circular_dependencies,
            re_export_cycles,
            package_cycles,
        },
        AnalysisResultsWorkspaceMergeParts {
            unused_catalog_entries,
            empty_catalog_groups,
            unresolved_catalog_references,
            unused_dependency_overrides,
            misconfigured_dependency_overrides,
        },
        AnalysisResultsFrameworkMergeParts {
            invalid_client_exports,
            mixed_client_server_barrels,
            misplaced_directives,
            unprovided_injects,
            unrendered_components,
            route_collisions,
            dynamic_segment_name_conflicts,
            unused_component_props,
            absent_component_props,
            constant_parameters,
            unused_component_emits,
            unused_component_inputs,
            unused_component_outputs,
            unused_svelte_events,
            unused_effect_layers,
            unused_tagged_errors,
            unproduced_catch_tags,
            unused_server_actions,
            unused_load_data_keys,
            unused_load_data_keys_global_abstain,
            prop_drilling_chains,
            thin_wrappers,
            duplicate_prop_shapes,
        },
        AnalysisResultsMetadataMergeParts {
            shared_state,
            cascade_hidden,
            cascade,
            suppression_count,
            unused_component_props_exempted,
            active_suppressions,
            feature_flags,
            security_findings,
            suppressed_security_findings,
            security_unresolved_edge_files,
            security_unresolved_callee_sites,
            security_unresolved_callee_diagnostics,
            export_usages,
            entry_point_summary,
            render_fan_in,
            react_component_intel,
            semantic_reachable_files,
            semantic_framework_contracts,
            constant_parameter_candidates,
        },
    )
}
