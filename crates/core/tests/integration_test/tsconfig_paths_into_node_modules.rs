use super::common::{create_config, fixture_path};

/// A tsconfig `paths` entry can point a lowercase scope such as `@components/*`
/// into an installed package. The import is an alias, so the package that the
/// target resolves into gets the dependency credit, not the specifier text.
#[test]
fn tsconfig_paths_into_node_modules_credit_the_target_package() {
    let root = fixture_path("tsconfig-paths-into-node-modules");
    let config = create_config(root);
    let results = fallow_core::analyze(&config).expect("analysis should succeed");

    let unlisted: Vec<&str> = results
        .unlisted_dependencies
        .iter()
        .map(|dep| dep.dep.package_name.as_str())
        .collect();
    assert!(
        unlisted.is_empty(),
        "tsconfig path aliases must not become unlisted dependencies: {unlisted:?}"
    );

    let unresolved: Vec<&str> = results
        .unresolved_imports
        .iter()
        .map(|import| import.import.specifier.as_str())
        .collect();
    assert!(
        unresolved.is_empty(),
        "tsconfig path aliases into node_modules must resolve: {unresolved:?}"
    );

    let unused: Vec<&str> = results
        .unused_dependencies
        .iter()
        .map(|finding| finding.dep.package_name.as_str())
        .chain(
            results
                .unused_dev_dependencies
                .iter()
                .map(|finding| finding.dep.package_name.as_str()),
        )
        .collect();
    assert!(
        !unused.contains(&"@acme/theme"),
        "the package behind the alias target must be credited: {unused:?}"
    );
    assert!(
        !unused.contains(&"react"),
        "a paths entry onto a declaration package must keep the runtime package credit: {unused:?}"
    );
}

/// Without an install, a tsconfig alias into a package directory that does
/// not exist credits that package, as for any bare import of an uninstalled
/// package. An alias into an installed package with a missing file stays an
/// unresolved import.
#[test]
fn tsconfig_paths_into_uninstalled_package_credit_the_target_package() {
    let root = fixture_path("tsconfig-paths-into-uninstalled-package");
    let config = create_config(root);
    let results = fallow_core::analyze(&config).expect("analysis should succeed");

    let unresolved: Vec<&str> = results
        .unresolved_imports
        .iter()
        .map(|import| import.import.specifier.as_str())
        .collect();
    assert_eq!(
        unresolved,
        vec!["@kit/missing"],
        "only the alias into the installed package with a missing file stays unresolved"
    );

    let unlisted: Vec<&str> = results
        .unlisted_dependencies
        .iter()
        .map(|dep| dep.dep.package_name.as_str())
        .collect();
    assert!(
        unlisted.is_empty(),
        "tsconfig path aliases must not become unlisted dependencies: {unlisted:?}"
    );

    let unused: Vec<&str> = results
        .unused_dev_dependencies
        .iter()
        .map(|finding| finding.dep.package_name.as_str())
        .collect();
    assert!(
        !unused.contains(&"@acme/theme"),
        "the uninstalled package behind the alias target must be credited: {unused:?}"
    );
}
