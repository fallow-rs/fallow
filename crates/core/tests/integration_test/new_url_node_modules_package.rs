//! A `new URL("./node_modules/<pkg>/...", import.meta.url)` path in a file that
//! a config file imports locates a file or a directory of an installed package.
//! The package is in use, so the dependency is not unused. See issue #4185.

use super::common::{create_config, fixture_path};

#[cfg_attr(miri, ignore)]
#[test]
fn new_url_into_node_modules_credits_the_package() {
    let root = fixture_path("new-url-node-modules-package");
    let config = create_config(root);
    let results = fallow_core::analyze(&config).expect("analysis should succeed");

    let unused: Vec<&str> = results
        .unused_dev_dependencies
        .iter()
        .map(|finding| finding.dep.package_name.as_str())
        .collect();
    assert_eq!(
        unused,
        ["idle-dep"],
        "a new URL path through node_modules credits the package"
    );
}
