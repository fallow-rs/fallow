//! Metro `resolver.extraNodeModules` maps a package name to a folder, often a
//! folder that a build step generates. An import of such a name is not an
//! unlisted dependency.

use std::fs;
use std::path::Path;

use super::common::create_config;

const METRO_CONFIG: &str = r#"const path = require("node:path");
const { getDefaultConfig } = require("@react-native/metro-config");

const config = getDefaultConfig(__dirname);
const generatedRoot = path.join(__dirname, ".generated", "assets");

config.resolver = {
  ...config.resolver,
  extraNodeModules: {
    ...config.resolver?.extraNodeModules,
    "@sample/generated-assets": generatedRoot,
  },
};
config.resolver.extraNodeModules = {
  ...config.resolver.extraNodeModules,
  generatedLicenses: path.join(__dirname, ".generated", "licenses"),
};

module.exports = config;
"#;

const APP_SOURCE: &str = r#"import assets from "@sample/generated-assets";
import { list } from "@sample/generated-assets/list";
import licenses from "generatedLicenses";
import missing from "not-listed-control";

export const value = [assets, list, licenses, missing];
"#;

fn write(root: &Path, path: &str, source: &str) {
    let path = root.join(path);
    fs::create_dir_all(path.parent().expect("parent")).expect("create directory");
    fs::write(path, source).expect("write fixture file");
}

#[test]
fn metro_extra_node_modules_keys_are_not_unlisted_dependencies() {
    let tmp = tempfile::tempdir().expect("create temp dir");
    let root = tmp.path();
    write(
        root,
        "package.json",
        r#"{
  "name": "metro-extra-node-modules",
  "main": "index.ts",
  "dependencies": { "react-native": "*" },
  "devDependencies": { "@react-native/metro-config": "*" }
}"#,
    );
    write(root, "metro.config.js", METRO_CONFIG);
    write(root, "index.ts", APP_SOURCE);

    let results = fallow_core::analyze(&create_config(root.to_path_buf())).expect("analysis");
    let unlisted: Vec<&str> = results
        .unlisted_dependencies
        .iter()
        .map(|finding| finding.dep.package_name.as_str())
        .collect();
    assert_eq!(
        unlisted,
        ["not-listed-control"],
        "only the package without a Metro mapping is unlisted"
    );
}
