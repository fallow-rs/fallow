pub(super) fn is_builtin(root: &str, slot: &str) -> bool {
    ECMASCRIPT.contains(&slot)
        || COMMON_HOST.contains(&slot)
        || (matches!(root, "window" | "self" | "globalThis") && BROWSER.contains(&slot))
        || (matches!(root, "global" | "globalThis") && NODE.contains(&slot))
}
